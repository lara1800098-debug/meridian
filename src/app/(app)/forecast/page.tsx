async function saveTarget(fd: FormData) {
  'use server';
  const u = await requireUser();
  assertCan(u, 'targets.edit');
  const amount = Number(fd.get('amount')), cur = String(fd.get('currency') ?? 'USD');
  const [fx] = await sql`SELECT per_usd FROM fx_rates WHERE currency = ${cur}`;
  const usd = amount / Number(fx?.per_usd ?? 1);
  const q = String(fd.get('quarter'));
  if (!/^\d{4}-Q[1-4]$/.test(q)) throw new Error('Quarter format: 2026-Q4');
  await sql`INSERT INTO targets (quarter, country, sector, track, amount_usd) VALUES (${q}, ${String(fd.get('country'))}, ${String(fd.get('sector'))}, ${String(fd.get('track'))}, ${usd})
    ON CONFLICT (quarter, country, sector, track) DO UPDATE SET amount_usd = EXCLUDED.amount_usd`;
  await audit(u.id, 'target.save', 'targets', q, { usd });
  revalidatePath('/forecast');
}

export default async function Forecast({ searchParams }: { searchParams: Promise<Record<string, string>> }) {
  const ctx = await pageCtx();
  const { t, lang, fx, cur, user } = ctx;
  assertCan(user, 'forecast');
  const q = await searchParams;
  const f = { country: sp(q.country) ?? 'ALL', sector: sp(q.sector) ?? 'ALL', track: sp(q.track) ?? 'ALL' };
  const q1 = quarterOf(), q2 = nextQuarter(q1);
  const [a, b] = await Promise.all([forecastFor(user, fx, q1, f), forecastFor(user, fx, q2, f)]);
  const m = (v: number) => money(v, cur, fx, lang);
  const st = await stages();
  const stageName = (k: string) => { const s = st.find((x) => x.key === k); return s ? (lang === 'ar' ? s.name_ar : s.name_en) : k; };
  const all = await loadDeals(user, fx, f);
  const ids = all.map((d) => d.id);

  // Pipeline generated by source (created this + last quarter)
  const bySource = new Map<string, number>();
  for (const d of all) bySource.set(d.source, (bySource.get(d.source) ?? 0) + d.tcv_usd);
  // Funnel from history
  const reached = ids.length ? await sql`SELECT DISTINCT deal_id, new_value AS stage FROM deal_history WHERE field = 'stage' AND deal_id = ANY(${ids})` : [];
  const order = st.filter((s) => !s.is_closed).map((s) => s.key).concat('won');
  const sets: Record<string, Set<string>> = {};
  for (const r of reached) { (sets[r.stage] ??= new Set()).add(r.deal_id); }
  // a deal at stage k implies it passed all earlier stages
  for (const d of all) { const idx = order.indexOf(d.stage); for (let i = 0; i <= idx; i++) (sets[order[i]] ??= new Set()).add(d.id); }
  const funnel = order.slice(0, -1).map((s, i) => ({ from: s, to: order[i + 1], n: sets[s]?.size ?? 0, rate: sets[s]?.size ? (sets[order[i + 1]]?.size ?? 0) / sets[s].size : null }));
  // Velocity: avg days in each stage from history transitions
  const vel = ids.length ? await sql`
    SELECT old_value AS stage, avg(extract(epoch FROM at - prev_at) / 86400)::float AS days, count(*)::int AS n FROM (
      SELECT deal_id, old_value, at, lag(at) OVER (PARTITION BY deal_id ORDER BY at) AS prev_at FROM deal_history WHERE field = 'stage' AND deal_id = ANY(${ids})
    ) x WHERE prev_at IS NOT NULL AND old_value IS NOT NULL GROUP BY 1` : [];
  const closed = all.filter((d) => d.status !== 'open');
  const reasons = new Map<string, number>();
  for (const d of closed.filter((d) => d.status !== 'won')) reasons.set(d.close_reason ?? 'other', (reasons.get(d.close_reason ?? 'other') ?? 0) + 1);
  const wr = (src: (s: string) => boolean) => { const c = closed.filter((d) => src(d.source)); return c.length ? c.filter((d) => d.status === 'won').length / c.length : null; };
  const wrM = wr((s) => s === 'meridian'), wrO = wr((s) => s !== 'meridian');
  const [s2m] = await sql`SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM h.at - p.created_at) / 86400)::float AS d, count(*)::int AS n
    FROM plays p JOIN deals d ON d.play_id = p.id JOIN deal_history h ON h.deal_id = d.id AND h.field = 'stage' AND h.new_value = 'engaged'`;
  const cov = (x: typeof a) => x.coverage.ratio;
  const covTone = (r: number | null, thr: number) => (r == null ? undefined : r >= thr ? 'good' : r >= thr * 0.66 ? 'warn' : 'bad');

  return (
    <Shell ctx={ctx} active="forecast">
      <PageHeader title={t('forecast.title')} subtitle={`${q1} · ${q2}`} />
      <form className="card mb-4 grid grid-cols-2 gap-3 p-4 md:grid-cols-4">
        <Select name="country" value={f.country} label={t('common.country')} options={[['ALL', t('countries.ALL')], ...COUNTRIES.map((c) => [c, t(`countries.${c}`)] as [string, string])]} />
        <Select name="sector" value={f.sector} label={t('common.sector')} options={[['ALL', t('sectors.ALL')], ...SECTORS.map((s) => [s, t(`sectors.${s}`)] as [string, string])]} />
        <Select name="track" value={f.track} label={t('common.track')} options={[['ALL', t('tracks.ALL')], ['enterprise', t('tracks.enterprise')], ['smb', t('tracks.smb')]]} />
        <div className="flex items-end"><button className="btn-ghost w-full">{t('common.apply')}</button></div>
      </form>

      {[a, b].map((x) => (
        <section key={x.quarter} className="mb-6">
          <h2 className="h2 mb-3">{x.quarter}</h2>
          <div className="grid grid-cols-2 gap-3 md:grid-cols-3 lg:grid-cols-6">
            <Kpi label={t('forecast.target')} value={x.target ? m(x.target) : '—'} sub={!x.target ? t('cockpit.noTarget') : undefined} />
            <Kpi label={t('forecast.commit')} value={m(x.commit)} />
            <Kpi label={t('forecast.weighted')} value={m(x.weighted)} />
            <Kpi label={t('forecast.realistic')} value={m(x.realistic)} sub={x.target ? `${Math.round((x.realistic / x.target) * 100)}% ${t('cockpit.ofTarget')}` : undefined} tone={x.target ? (x.realistic >= x.target ? 'good' : x.realistic >= x.target * 0.8 ? 'warn' : 'bad') : undefined} />
            <Kpi label={t('forecast.coverage')} value={cov(x) != null ? `${cov(x)!.toFixed(1)}×` : '—'} sub={`${t('forecast.remaining')}: ${m(x.coverage.remaining)}`} tone={covTone(cov(x), x.coverageThreshold)} />
            <Kpi label={t('forecast.concentration')} value={`${Math.round(x.concentration.share * 100)}%`} sub={t('forecast.concentrationText', { pct: Math.round(x.concentration.share * 100), q: x.quarter, n: x.concentration.n })} tone={x.concentration.share > 0.6 ? 'warn' : undefined} />
          </div>
          {cov(x) != null && cov(x)! < x.coverageThreshold && <p className="mt-2 text-sm text-bad">⚠ {t('cockpit.belowCoverage', { x: x.coverageThreshold })}</p>}
        </section>
      ))}

      <div className="grid gap-4 lg:grid-cols-2">
        <Card title={t('forecast.method')}>
          <p className="text-sm text-ink-2">
            {a.realMethod.method === 'historical'
              ? `Σ value × historical win rate from stage × health factor × (1 − slippage ${Math.round(a.realMethod.slippage * 100)}%). Based on ≥ 10 closed deals.`
              : 'Σ value × stage probability × health factor (Healthy 1.0 · Watch 0.8 · At risk 0.5). Switches to historical win and slippage rates automatically once 10+ deals have closed.'}
          </p>
          <table className="table mt-3"><thead><tr><th>{t('common.title')}</th><th>p</th><th>×</th><th>{t('forecast.realistic')}</th></tr></thead>
            <tbody>{a.realMethod.lines.slice(0, 8).map((l) => { const d = a.open.find((o) => o.id === l.id)!; return <tr key={l.id}><td className="text-xs">{d.title}</td><td className="font-num text-xs">{Math.round(l.p)}%</td><td className="font-num text-xs">{l.hf}</td><td className="font-num text-xs">{m(l.v)}</td></tr>; })}</tbody></table>
        </Card>
        <Card title={t('forecast.generated')}><HBar unit="" data={[...bySource].map(([k, v]) => ({ name: t(`deals.sources.${k}`), value: Math.round(fromUsd(v, cur, fx)) }))} /></Card>
        <Card title={t('forecast.funnel')}>
          <table className="table"><tbody>{funnel.map((r) => <tr key={r.from}><td className="text-sm">{stageName(r.from)} → {stageName(r.to)}</td><td className="font-num">{r.rate != null ? `${Math.round(r.rate * 100)}%` : '—'}</td><td className="text-xs text-ink-3">n={r.n}</td></tr>)}</tbody></table>
        </Card>
        <Card title={t('forecast.velocity')}>
          <HBar data={st.filter((s) => !s.is_closed).map((s) => ({ name: stageName(s.key), value: Math.round(vel.find((v) => v.stage === s.key)?.days ?? 0) }))} />
          <p className="text-xs text-ink-3">{t('common.days')} · norm: {st.filter((s) => !s.is_closed).map((s) => `${stageName(s.key)} ${s.norm_days}`).join(' · ')}</p>
        </Card>
        <Card title={t('forecast.winloss')}>
          <HBar data={[...reasons].map(([k, v]) => ({ name: t(`deals.lossReasons.${k}`), value: v }))} />
          <p className="mt-2 text-sm">{t('forecast.winRate')} — {t('forecast.meridianVsOther')}: <span className="font-num font-semibold">{wrM != null ? `${Math.round(wrM * 100)}%` : '—'}</span> vs <span className="font-num font-semibold">{wrO != null ? `${Math.round(wrO * 100)}%` : '—'}</span></p>
          <p className="mt-1 text-sm">{t('forecast.signalToMeeting')}: <span className="font-num font-semibold">{s2m?.d != null ? Math.round(s2m.d) : '—'}</span> <span className="text-xs text-ink-3">(n={s2m?.n ?? 0})</span></p>
        </Card>
        {can(user, 'targets.edit') && (
          <Card title={t('forecast.targets')}>
            <form action={saveTarget} className="grid grid-cols-2 gap-3 sm:grid-cols-3">
              <Field label="Quarter" name="quarter" defaultValue={q1} required />
              <Select name="country" value="ALL" label={t('common.country')} options={[['ALL', t('countries.ALL')], ...COUNTRIES.map((c) => [c, t(`countries.${c}`)] as [string, string])]} />
              <Select name="sector" value="ALL" label={t('common.sector')} options={[['ALL', t('sectors.ALL')], ...SECTORS.map((s) => [s, t(`sectors.${s}`)] as [string, string])]} />
              <Select name="track" value="ALL" label={t('common.track')} options={[['ALL', t('tracks.ALL')], ['enterprise', t('tracks.enterprise')], ['smb', t('tracks.smb')]]} />
              <Field label={t('common.value')} name="amount" type="number" required />
              <Select name="currency" value={cur} label={t('common.currency')} options={Object.keys(fx).map((c) => [c, c])} />
              <div><button className="btn-primary">{t('common.save')}</button></div>
            </form>
            <TargetsList cur={cur} fx={fx} lang={lang} t={t} />
          </Card>
        )}
      </div>
    </Shell>
  );
}

async function TargetsList({ cur, fx, lang, t }: { cur: string; fx: Record<string, number>; lang: 'en' | 'ar'; t: any }) {
  const rows = await sql`SELECT * FROM targets ORDER BY quarter DESC, country, sector, track LIMIT 50`;
  return (
    <table className="table mt-3"><tbody>{rows.map((r) => <tr key={r.id}><td className="text-xs">{r.quarter}</td><td className="text-xs">{t(`countries.${r.country}`)} · {t(`sectors.${r.sector}`)} · {t(`tracks.${r.track}`)}</td><td className="font-num text-xs">{money(Number(r.amount_usd), cur, fx, lang)}</td></tr>)}</tbody></table>
  );
}
